        output_folder, file_with_extension = os.path.split(OutputFile)
        output_filename, _ = os.path.splitext(file_with_extension)
        msg(output_folder)
        msg(output_filename)

        save_temp_layer_to_gpkg(merge, str(output_filename), output_folder + "/")

