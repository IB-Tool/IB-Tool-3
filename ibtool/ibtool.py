        potential_paths = [
            '/usr',
            '/usr/local',
            '/Applications/QGIS.app/Contents/MacOS'
        ]
        for path in potential_paths:
            if os.path.exists(os.path.join(path, 'bin', 'qgis')) or \
               os.path.exists(os.path.join(path, 'bin', 'qgis.bin')):
                qgis_prefix = path
                break

